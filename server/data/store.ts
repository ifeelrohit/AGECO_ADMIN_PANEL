  public recordAudit(actor: { id: string; name: string; role: UserRole }, action: AuditLog['action'], module: string, resourceId: string, details: string, diffSummary?: string, ip = '127.0.0.1') {
    const log: AuditLog = {
      id: `aud-log-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
      actorId: actor.id,
      actorName: actor.name,
      actorRole: actor.role,
      ipAddress: ip,
      action,
      module,
      resourceId,
      details,
      diffSummary,
      createdAt: new Date().toISOString(),
    };
    this.auditLogs.unshift(log);
    if (this.auditLogs.length > 300) {
      this.auditLogs.pop();
    }
    return log;
  }
